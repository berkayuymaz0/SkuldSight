  // Metin içindeki {anahtar} yer tutucularını vars nesnesindeki değerlerle değiştirir.
  function interpolate(str, vars) {
    if (!str || !vars) {
      return str;
    }
    return str.replace(/\{(\w+)\}/g, function (_, k) {
      return Object.prototype.hasOwnProperty.call(vars, k)
        ? String(vars[k])
        : '{' + k + '}';
    });
  }

  // Geçerli arayüz dil kodunu (__VT_LANG__) döndürür; yoksa 'en' kullanılır.
  function vtLang() {
    return global.__VT_LANG__ || 'en';
  }

  // Seçili dil tablosundan çeviri metnini alır; eksik anahtarda İngilizceye veya anahtara düşer.
  function vtT(key, vars) {
    const lang = vtLang();
    const table = M[lang] || M.en;
    const fallback = M.en;
    let s = table[key];
    if (s === undefined) {
      s = fallback[key];
    }
    if (s === undefined) {
      return key;
    }
    return vars ? interpolate(s, vars) : s;
  }

